#!/usr/bin/env python3
"""Everything that can disqualify the submission, checked mechanically.

Four failure modes, none of which the compiler complains about, and all of which are found by reading the
wrong thing (the draft, rather than the file that gets uploaded):

  identity   double-blind. pdflatex writes an Info dictionary, hyperref writes another, and each embedded
             figure carries a third; any of them can hold an absolute path with a username in it.
  format     the style file's own limits. A margin, font or line-spacing change to gain space is what a
             format check looks for first, and the 9-page body limit is measured on the compiled PDF, not
             estimated from a word count.
  content    an anonymised paper can still name its authors in prose: an acknowledgement, a funding line,
             "our previous work [12]", a repository URL.
  build      undefined citations and overfull boxes reach the reader as "[?]" and text in the margin. Both
             are one line in a 2000-line log.

  python3 audit_submission.py            # -> exit 0 only if every check passes

Anything printed FAIL blocks submission. WARN is for what a human should look at once.
"""
from __future__ import annotations

import getpass
import glob
import hashlib
import importlib.util
import json
import os
import re
import subprocess
import sys

AN = os.path.dirname(os.path.abspath(__file__))
PDF = f"{AN}/paper/main.pdf"
LOG = f"{AN}/paper/main.log"
TEX = f"{AN}/paper/main.tex"
BODY_PAGES = 9          # the workshop's long-paper limit, references and appendix excluded
BOOT_TOL = 0.02         # the tolerance reproduce.py gives a bound it resamples with its own seed
BUNDLE = f"{AN}/release/aina2026_agent_reviewers"

# The one link to the release a double-blind submission may carry. A repository URL names an account, so the
# rule is that no such address reaches the page; an anonymising proxy is the exception, because the address it
# serves the files from is generated by the proxy and resolves to nobody. Empty means the paper carries no link
# at all, which is what the checks below then enforce. Setting it does not widen the rule: its host has to be
# the proxy, no other address on that host may be printed, and it has to appear on a page rather than sit in a
# source file the reader never sees.
ARTIFACT_URL = "https://anonymous.4open.science/r/ai-reviewer-panel-917A"
ARTIFACT_HOST = "anonymous.4open.science"
# Hosts the reference list is allowed to print. Every entry here is a third-party citation, so the address
# names the cited work rather than an author of this one; anything else on a page is a leak whatever it points
# at, which is why this is a list of what may appear and not a list of what may not.
CITATION_HOSTS = {"arxiv.org"}

# Appendix G lists what the release contains. That list is prose, and a bullet naming an artifact is a claim
# that nothing compiles, runs or resamples -- reproduce.py reads the bundle and so can only be wrong about a
# number, never about a file the bundle does not have. It was wrong: one bullet promised the presentation
# transform scripts "with the transformed texts they produced", and no text corpus ships. Section 10 of the
# body says the de-identified texts are not redistributed, so the two inventories contradicted each other and
# the reader was pointed at an artifact they cannot open.
#
# So each bullet is checked in both directions: the phrase must be on the page, and the glob must match at
# least one file that ships. The bullet count is checked too, because a new bullet with no glob is a promise
# nothing tests -- which is how the last one got in. What this cannot see is a bullet that names two things and
# ships one: the phrase matched, the glob matched, and the second noun was fiction. Hence the last entries,
# which are phrases a bullet may not contain.
INVENTORY = [
    ("prompt template", "instrument/reviewer_prompt_iclr.md"),
    ("JSON schema", "instrument/metrics_schema.json"),
    ("slot specification", "instrument/slots*.json"),
    ("gate definition", "instrument/score_against_gate.py"),
    ("every review from every panel", "reviews/*/**/[RC]?.json"),
    ("the calibration parameters", "calibration/calibration_params_*.json"),
    ("the de-identification pipeline", "scripts/deid_*.py"),
    ("the presentation-transform scripts", "scripts/pia_transforms.py"),
    ("the analysis scripts", "scripts/analyze.py"),
    ("ICLR 2026 frame", "frame/iclr2026_frame.json"),
    ("document measurements", "data/extract_corpus.json"),
]
# A bullet promising a corpus of texts. Every text the studies scored is either a third-party manuscript the
# release does not redistribute or this paper's own extract, which package_release.py refuses by name, so no
# spelling of this promise can be kept -- it is a claim to fix in the appendix, not a file to add.
NO_SUCH_ARTIFACT = ("transformed texts", "the texts they produced", "manuscript.txt", "de-identified texts")

ONES = ("zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen "
        "sixteen seventeen eighteen nineteen").split()
TENS = "twenty thirty forty fifty sixty seventy eighty ninety".split()

# Derived, not typed: a checker that spells out the author's username has put it in the repository it is
# checking, and would only ever work on one machine.
IDENTITY = sorted({getpass.getuser(), os.path.basename(os.path.expanduser("~"))} - {"", "root"})

fails: list[str] = []
warns: list[str] = []


def check(ok, label, detail=""):
    print(f"  {'ok  ' if ok else 'FAIL'} {label}{'  -- ' + detail if detail and not ok else ''}")
    if not ok:
        fails.append(f"{label}: {detail}")


def warn(cond, label, detail=""):
    if cond:
        print(f"  WARN {label}  -- {detail}")
        warns.append(label)


def spell(n):
    """-> the English word for a count under a hundred, hyphenated as the appendix writes one."""
    assert 0 <= n < 100, f"extend spell() past {n}"
    if n < 20:
        return ONES[n]
    t, u = divmod(n, 10)
    return TENS[t - 2] + (f"-{ONES[u]}" if u else "")


def pdftext(path, layout=True):
    cmd = ["pdftotext"] + (["-layout"] if layout else []) + [path, "-"]
    return subprocess.run(cmd, capture_output=True, text=True).stdout


def main():
    for f in (PDF, LOG, TEX):
        if not os.path.exists(f):
            print(f"missing {f}: run md2tex.py then pdflatex")
            return 2
    raw = open(PDF, "rb").read()
    txt = pdftext(PDF)
    tex = open(TEX, encoding="utf-8").read()
    log = open(LOG, encoding="utf-8", errors="replace").read()
    pages = txt.split("\f")

    print("\nidentity")
    info = dict(re.findall(r"^(\w+):[ \t]*(.*)$", subprocess.run(
        ["pdfinfo", PDF], capture_output=True, text=True).stdout, re.M))
    for field in ("Author", "Title", "Subject", "Keywords"):
        v = info.get(field, "").strip()
        check(v == "", f"PDF {field} empty", repr(v))
    # An absolute path is the leak that survives every prose audit: it is in the file, not in the text.
    for label, pat in (("no absolute paths", rb"/(?:home|Users)/[\w./-]+"),
                       ("no local username", "|".join(IDENTITY).encode()),
                       ("no email address", rb"[\w.\-]+@[\w.\-]+\.[a-z]{2,}"),
                       ("no ORCID", rb"(?i)orcid")):
        hits = sorted({h[:70] for h in re.findall(pat, raw)})
        # Short fragments of a name occur inside compressed streams as byte noise; require a real word.
        hits = [h for h in hits if not re.fullmatch(rb"(?i)[a-z]{1,3}", h)]
        check(not hits, label, str(hits[:4]))

    # Two surfaces, because they fail differently. A URL sitting in an embedded figure or an Info dictionary
    # never renders and is found by anyone who opens the file; a URL on a page is read by a reviewer, and
    # because the streams are compressed it does not appear in the bytes at all. Searching only the bytes
    # would report clean while the page carried an address.
    allowed = {ARTIFACT_URL} if ARTIFACT_URL else set()
    inbytes = {h.decode("latin-1") for h in re.findall(rb"https?://[^\s)>\]}]{6,}", raw)}
    check(not (inbytes - allowed), "no URL in the file beyond the artifact link",
          str(sorted(inbytes - allowed)[:4]))

    # Read back with -layout, every body line begins with its printed line number, and a long link is broken
    # across lines at a dot or a slash. So the number is dropped, the spaces are removed, and each line is read
    # together with the one after it; an address is attributed to the line it starts on, which is what joins a
    # broken link without also reading a truncated half of the next one.
    tight = [re.sub(r"\s", "", re.sub(r"^\s*\d{1,4}(?=\s)", "", ln)) for ln in txt.split("\n")]

    def onpage(pat):
        """-> every match of `pat` in the printed text, counted once at the line where it begins."""
        out = []
        for i, cur in enumerate(tight):
            window = cur + (tight[i + 1] if i + 1 < len(tight) else "")
            out += [m for m in re.finditer(pat, window) if m.start() < len(cur)]
        return out

    # By host, because a page URL is normal in this paper: the reference list prints one for every arXiv entry.
    # What matters is whose account an address names. A citation host names a third party, and the proxy
    # generates its own address, so those are the two kinds of link a blind submission may print.
    hosts = {m.group(1).lower() for m in onpage(r"https?://([^/\s,;)\]}]{4,})")}
    stray = hosts - CITATION_HOSTS - ({ARTIFACT_HOST} if ARTIFACT_URL else set())
    check(not stray, "every printed link is a citation or the anonymous mirror", str(sorted(stray)[:4]))
    if ARTIFACT_URL:
        host = re.sub(r"^https?://([^/]+).*$", r"\1", ARTIFACT_URL)
        check(host == ARTIFACT_HOST, "the artifact link is served by the anonymising proxy",
              f"{host!r} is not {ARTIFACT_HOST!r}, so the address can be traced to an account")
        shown = len(onpage(re.escape(re.sub(r"\s", "", ARTIFACT_URL))))
        check(shown >= 1, "the artifact link is printed on a page",
              "it is set in the sources and not in the rendered text, so no reader can follow it")
        # The host check passes any path on the proxy, and a stale path serves a different tree than the one
        # this paper was audited against, so the addresses on that host have to be the declared one and no other.
        check(shown == len(onpage(re.escape("://" + ARTIFACT_HOST))),
              "the only mirror address printed is the declared one",
              f"{shown} printings of the declared link against "
              f"{len(onpage(re.escape('://' + ARTIFACT_HOST)))} on its host")
    check("Anonymous Author(s)" in txt, "author block is anonymous")
    for label, pat in (("no acknowledgements", r"(?im)^\s*acknowledge?ments?\b"),
                       ("no funding line", r"(?i)grant no\.?|funded by|supported by (a|the) \w+ (grant|award)"),
                       ("no affiliation", r"(?i)(University|Institute|Laborator(y|ies)) of \w+"),
                       ("no identifying self-citation", r"(?i)our (previous|earlier|prior) (paper|work) \["),
                       ("no repository URL", r"(?i)(github|gitlab|huggingface|zenodo|osf)\."),
                       # A comment in the source is addressed to whoever regenerates a table, and LaTeX has no
                       # reason to hide it. Two of these printed on a page of the appendix. pdflatex turns the
                       # "--" into an en dash on the way, so the pattern has to match the printed form too.
                       ("no markup comment left in the text", r"<!\s*[-\u2013]{1,2}|[-\u2013]{1,2}\s*>"),
                       ("no generator marker left in the text", r"(?i)generated by \S+\.(py|sh)"),
                       ("no drafting marker left in the text", r"\b(TODO|FIXME|XXX|TO BE WRITTEN|PLACEHOLDER)\b")):
        m = re.findall(pat, txt)
        check(not m, label, str(m[:3]))

    print("\nfonts")
    # The submitted file is the artifact, and its font table is a statement about itself that nothing else in
    # this audit reads. Two defects hid there at once. Every dollar-sign span on a figure was set by the maths
    # engine in its own default family, so the figures carried two typefaces and the only place that showed was
    # this table. And the Helvetica the figures moved to ships as an OpenType face whose outlines are in CFF,
    # which matplotlib writes out while declaring the font TrueType; readers sniff the file and draw it anyway,
    # so the page looked right while the font dictionary described a file that was not there. Neither is visible
    # in a rendering, at any zoom, which is why the check is on the table rather than on the page.
    fonts = subprocess.run(["pdffonts", PDF], capture_output=True, text=True)
    rows = [ln for ln in fonts.stdout.splitlines()[2:] if ln.strip()]
    check(rows, "the built PDF reports its fonts",
          "pdffonts returned nothing, so the three checks below are blind -- install poppler-utils")
    check(not fonts.stderr.strip(), "no font is embedded under a false type",
          " / ".join(sorted(set(fonts.stderr.split("\n")))[:3]))
    faces = [(r[:36].strip(), r[36:54].strip(), r[54:71].strip(), r[71:75].strip()) for r in rows]
    check(all(emb == "yes" for _, _, _, emb in faces), "every font is embedded",
          str([n for n, _, _, e in faces if e != "yes"][:4]))
    check(not [n for n, t, _, _ in faces if "Type 3" in t], "no Type 3 font",
          str([n for n, t, _, _ in faces if "Type 3" in t][:4]))
    # The figures' faces are the CID-keyed ones; the body's are the Type 1 faces LaTeX installs. Requiring one
    # family of the former is what would have named the mixed-typeface figures: the subset tag before the "+" is
    # per-object, so it is dropped, and a "-Bold" or "-Italic" cut is the same family as its regular.
    fig_fam = {re.sub(r"^[A-Z]{6}\+", "", n).split("-")[0] for n, t, _, _ in faces if "CID" in t}
    check(len(fig_fam) <= 1, "the figures are set in one typeface", ", ".join(sorted(fig_fam)))

    print("\nformat")
    check("dblblindworkshop" in tex, "style option dblblindworkshop (anonymised submission mode)")
    check("\\linenumbers" in log or "lineno" in log or re.search(r"^\s*1\s", txt, re.M) is not None,
          "line numbers present (the style file's submission mode)")
    for label, pat in (("no margin change", r"\\geometry|\\addtolength\s*\{\s*\\(?:textwidth|textheight|oddsidemargin|topmargin|evensidemargin)\}"),
                       ("no font-size change", r"\\fontsize|\\renewcommand\s*\{?\\(normalsize|baselinestretch)"),
                       ("no line-spacing change", r"\\linespread|\\setstretch|\\baselineskip\s*="),
                       ("no vertical-space theft around floats", r"\\setlength\s*\{?\\(floatsep|intextsep|textfloatsep|abovedisplayskip)")):
        m = re.findall(pat, tex)
        check(not m, label, str(m[:3]))

    # The page limit, measured. lineno numbers every body line, so the last numbered line before the
    # References heading is where the body ends -- and which page that falls on is the only fact that counts.
    ref_page = next((i for i, p in enumerate(pages, 1) if re.search(r"^\s*\d*\s*References\s*$", p, re.M)), None)
    check(ref_page is not None, "References heading found", "no References heading in the PDF")
    if ref_page:
        body_tail = pages[ref_page - 1][:pages[ref_page - 1].find("References")]
        spill = [ln for ln in body_tail.splitlines() if re.sub(r"^\s*\d{1,3}\s*", "", ln).strip()]
        check(ref_page - 1 <= BODY_PAGES, f"body within {BODY_PAGES} pages",
              f"references start on page {ref_page}, so the body runs to page {ref_page - 1 if not spill else ref_page}")
        check(not spill or ref_page - 1 < BODY_PAGES, f"no body text on page {BODY_PAGES + 1}",
              f"{len(spill)} line(s) of body text share the references page: {spill[:2]}")
        print(f"  ..   body ends page {ref_page - 1 if not spill else ref_page}, "
              f"references start page {ref_page}, {len(pages) - 1} pages total")

    print("\nbuild")
    for label, pat in (("no undefined citations", r"Citation `[^']+' on page \d+ undefined"),
                       ("no undefined references", r"LaTeX Warning: Reference `[^']+' on page \d+ undefined"),
                       ("no missing figure", r"File `[^']+' not found"),
                       ("no overfull box", r"Overfull \\hbox \((\d+\.\d+)pt too wide\)")):
        m = re.findall(pat, log)
        check(not m, label, f"{len(m)} in main.log, e.g. {m[:2]}")
    check("[?]" not in txt.replace("[?]t", ""), "no unresolved [?] citation marker in the PDF")
    warn(bool(re.findall(r"Underfull \\vbox", log)), "underfull vboxes",
         f"{len(re.findall(r'Underfull .vbox', log))} -- float placement stretched a page, cosmetic only")
    # Appendix G used to report a scoring run of this manuscript, and everything between here and the staleness
    # checks below verified that the run and the disclosure agreed: that the body scored was the body being
    # submitted, that the extract the panel read was the one build.txt recorded, and that the appendix and the
    # opening figure both printed the run on disk. The paper makes none of those promises now. No manuscript of
    # ours is scored, described as study material or released, and the opening figure's focal marker is a corpus
    # paper the figure script selects by score.
    #
    # So the check inverts, and the inverted form is the cheaper one to keep true: nothing in the paper may
    # report a scoring run of itself. Three conjuncts, because a reinstatement can arrive three ways -- a row in
    # the expectation table, a path in the prose, or the composite itself in a sentence.
    #
    # The expectation table first. Every number the paper prints has a row there, so a self-score cannot reach
    # the page without one, and the rows that named this manuscript were spelled "this paper's ..." for as long
    # as they existed. This is the conjunct that cannot be evaded by rewording, since the row is what makes the
    # number printable at all.
    rp_src = open(f"{AN}/reproduce.py", encoding="utf-8").read()
    self_rows = re.findall(r'\(\s*"[^"]+",\s*"(this paper\'s[^"]*|build \d+[^"]*|self-review[^"]*)"', rp_src)
    check(not self_rows, "the expectation table has no row for a score of this paper",
          f"reproduce.py still carries {self_rows[:3]} -- a self-score with a row is a self-score the paper is "
          f"entitled to print")
    # Then the paths. A sentence citing the reviews of this manuscript is a claim about a directory the release
    # no longer contains, which package_release.py reports as a promised path that is missing; caught here as
    # well because the diagnostic there names the bundle and this one names the sentence.
    md = {f: open(f"{AN}/{f}", encoding="utf-8").read() for f in ("DRAFT.md", "APPENDIX.md")}
    paths = sorted({f"{f}: {m.group(0)}" for f, t in md.items()
                    for m in re.finditer(r"reviews/self\w*|self_review|self_score\.json|run_self\.sh|"
                                         r"score_self\.py|self-review", t)})
    check(not paths, "the paper names no review of itself",
          f"{paths[:4]} -- the disclosure those pointed at is gone, so the sentence has to go with it")
    # And the composite, in the one form a disclosure states it in. Read from disk rather than typed: the run
    # that produced the numbers the paper used to print is still in the working directory, so it is exactly the
    # value to search for. Matched only where the page presents it as a z, since a corpus quantity three places
    # long collides with one of these magnitudes often enough that an unqualified search would fail on a table
    # of composites that has nothing to do with this paper.
    ss = f"{AN}/self_review/self_score.json"
    if os.path.exists(ss):
        sj = json.load(open(ss))
        zs = {sj["composite"], sj.get("panel_gap")} | set((sj.get("per_panel") or {}).values())
        seen = sorted({f"{f}: {v:.3f} z" for f, t in md.items() for v in zs
                       if isinstance(v, (int, float)) and abs(v) >= 0.01
                       and re.search(rf"[+-−]?{re.escape(f'{abs(v):.3f}')}\s*z\b", t)})
        check(not seen, "the paper prints no composite from a scoring run of itself",
              f"{seen} -- self_score.json produced that value, and a paper that reports its own score is one "
              f"whose score changes the text that was scored")

    # The generated tex must be newer than what generates it, or the audit passed on a stale PDF.
    # main.tex was missing from this list, and it is the one input pdflatex reads directly: the title, the
    # abstract and the appendix intro all live there, so an edit to any of them left a stale PDF that every
    # check here passed while reading the previous typesetting.
    for src, gen in (("DRAFT.md", "paper/body.tex"), ("APPENDIX.md", "paper/appendix.tex"),
                     ("paper/body.tex", "paper/main.pdf"), ("paper/main.tex", "paper/main.pdf")):
        check(os.path.getmtime(f"{AN}/{gen}") >= os.path.getmtime(f"{AN}/{src}") - 1,
              f"{gen} not stale w.r.t. {src}", "re-run md2tex.py and pdflatex")

    # The figure the paper embeds must be the figure the figure script wrote. This is a byte comparison and
    # not an mtime one, because the failure it exists for was silent for eleven hours: paper/figs was a
    # hand-made copy of figs, nothing in the build refreshed it, and every other check here compares .tex to
    # .md or .pdf to .tex -- none of them looks at what a \includegraphics actually points at. build.sh now
    # copies before typesetting; this fails if anyone typesets without it.
    stale = [os.path.basename(f) for f in sorted(glob.glob(f"{AN}/figs/*.pdf"))
             if not (os.path.exists(f"{AN}/paper/figs/{os.path.basename(f)}")
                     and open(f, "rb").read() == open(f"{AN}/paper/figs/{os.path.basename(f)}",
                                                      "rb").read())]
    check(not stale, "the embedded figures are the ones the figure scripts wrote",
          f"paper/figs differs from figs for {stale} -- run build.sh, which copies them")

    # "Figure 3(a)" is a number a writer types and LaTeX derives, so the two can disagree and nothing
    # complains. They did: inserting a method figure at the front of the body renumbered all four of the
    # others, and the eight references to them are plain text in two files. Both halves are derivable, so
    # both are derived here -- the figures from the order they appear in, the references from the prose --
    # and the pairing is checked from each side. An out-of-range reference is a certain error. An
    # unreferenced figure is the shape a missed renumbering leaves behind, because a reference that failed to
    # move keeps pointing at the figure that used to hold that number and orphans the one that now does.
    #
    # A caption is one markdown image, and it is not one line: the opening figure's runs over two, so a
    # pattern anchored to "![" and ".pdf)" in the same line saw four figures out of five, numbered them one
    # to four, and reported the body's correct reference to Figure 5 as out of range. The opener and the
    # closer are matched separately now. The number of figures is then compared against the count LaTeX will
    # actually typeset, because that is the half of this check that has no other witness: an undercount
    # renumbers every figure after the one it misses and still passes both halves above.
    order, cited = [], {}
    for path in ("DRAFT.md", "APPENDIX.md"):
        opened = False
        for line in open(f"{AN}/{path}", encoding="utf-8"):
            s = line.strip()
            opened = opened or s.startswith("![")
            m = re.search(r"\]\((figs/(F\d)\.pdf)\)$", s)
            if m and opened:
                order.append(m.group(2))
                opened = False
            for r in re.finditer(r"Figure (\d+)", line):
                cited.setdefault(int(r.group(1)), []).append(path)
    numbers = {f: i + 1 for i, f in enumerate(order)}
    typeset = [f for gen in ("paper/body.tex", "paper/appendix.tex")
               for f in re.findall(r"includegraphics[^{]*\{[^}]*?(F\d)\.pdf\}",
                                   open(f"{AN}/{gen}", encoding="utf-8").read())]
    check(order == typeset, "the figures read out of the markdown are the ones the document typesets",
          f"the markdown gives {order} and the .tex files give {typeset}, so the numbering this check "
          f"derives is not the numbering the reader sees")
    over = sorted(n for n in cited if n > len(order))
    check(not over, "every figure reference is in range",
          f"the paper cites Figure {over} and typesets {len(order)}: {numbers}")
    # The opening figure was exempt here while it was the one a caption alone had to carry. It is not any
    # more: a figure that draws the whole instrument is worthless if no sentence sends a reader to it, and
    # nothing in the paper did. The exemption is gone, so every figure now has to be named in the prose.
    orphan = sorted(n for f, n in numbers.items() if n not in cited)
    check(not orphan, "every figure the paper typesets is referred to in the prose",
          f"Figure {orphan} is typeset and never mentioned, which is what a missed renumbering leaves: "
          f"{numbers}")

    # How a signed number is spelled, checked on the rendered page rather than in the source. figstyle.py's
    # whole reason for existing is that matplotlib draws a tick label with U+2212 and an f-string writes an
    # ASCII hyphen, so a panel can annotate itself in a different glyph from its own axis; it says this check
    # is what enforces the convention, and until now it did not exist. The same rule covers the body, where
    # md2tex maps U+2212 to $-$: a hyphen typed into a table cell sets shorter than the minus in the column
    # above it and no log line mentions it.
    #
    # A sign is a hyphen before a digit that is not part of a word, which is what keeps "gpt-5.5" and
    # "opus-4.8" -- five of them in one figure's legend -- out of the count. The reverse case is a minus that
    # has landed inside a word, which is what "non$-$allotted" would look like after conversion; a minus with
    # a space on each side is an operator and is left alone.
    SIGN = re.compile(r"(?<![\w.])-(?=\d)")
    WORDY = re.compile(r"−(?=[A-Za-z])|(?<=[A-Za-z])−")
    for f in sorted(glob.glob(f"{AN}/figs/*.pdf")) + [PDF]:
        t = pdftext(f, layout=False)
        rel = os.path.relpath(f, AN)
        for label, pat, why in (("hyphen", SIGN, "a signed number spelled with an ASCII hyphen"),
                                ("minus", WORDY, "a minus sign inside a word")):
            hits = sorted({" ".join(t[max(0, m.start() - 16):m.start() + 10].split())
                           for m in pat.finditer(t)})
            check(not hits, f"{rel}: no {label} where the other glyph belongs",
                  f"{len(hits)} case(s) of {why}: {hits[:3]}")

    # Anywhere the paper names its own title. The check further up compares main.tex's title against the scored
    # extract, which is the title and the body. APPENDIX.md used to open by naming the paper it supports, which
    # made sense while that paragraph stayed in the source: it never reached the PDF, so it was the only line
    # saying which paper the file belonged to, and after a retitle it named the previous one. The paragraph is
    # now the appendix's own opening on the page, a few pages after the title itself, so naming the title there
    # is a restatement rather than a label -- and the drift it was guarding against is what the superseded-title
    # sweep below decides, over the whole file rather than one paragraph of it.
    #
    # The list of superseded titles is not typed. Every archived self-review kept the extract its panel read,
    # and an extract opens with that build's title, so the titles this paper has had are a fact on disk. A typed
    # list would need a line added at each retitle, which is the same maintenance the retitle just failed.
    m = re.search(r"\\title\{(.+?)\}", open(f"{AN}/paper/main.tex", encoding="utf-8").read(), re.S)
    if m:
        want = re.sub(r"\s+", " ", m.group(1).replace("\\\\", " ").replace("\\", "")).strip()
        key = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())        # noqa: E731  quoting style is not the point
        apx_intro = " ".join(open(f"{AN}/APPENDIX.md", encoding="utf-8").read().split("\n\n")[1].split())
        check(key(want) not in key(apx_intro),
              "the appendix does not restate the title it is bound to",
              "APPENDIX.md's opening paragraph repeats the title, which is on page one of the same document")
        old = set()
        for f in sorted(glob.glob(f"{AN}/self_review/reviews_earlier_build*/deid_earlier/manuscript.txt")):
            first = open(f, encoding="utf-8", errors="replace").readline().strip()
            # A title long enough to wrap sets on two lines, so the extract's first line is a prefix of it and
            # not the whole of it. Equality therefore read the current title, archived under its own build, as a
            # superseded one and failed on both source files at once. Prefix in either direction is the same
            # title: the archived line is the current title cut at the page's line break, or the current title
            # is what that build's line was cut to. Only a line that is neither is a title this paper has left.
            if first and not (key(want).startswith(key(first)) or key(first).startswith(key(want))):
                old.add(first)
        # The figure scripts are in scope because they ship, and one of them framed its own design as "one
        # panel per half of the title" -- a description that outlived two titles without the panels changing.
        for src in ["DRAFT.md", "APPENDIX.md"] + [os.path.relpath(p, AN) for p in
                                                  sorted(glob.glob(f"{AN}/fig?.py"))]:
            txt = key(open(f"{AN}/{src}", encoding="utf-8").read())
            hits = sorted(t for t in old if key(t) in txt)
            check(not hits, f"{src} carries no superseded title", str(hits))

    # The appendix roadmap, against the appendix. The paragraph under the appendix's own heading tells the
    # reader which letter holds what, and LaTeX assigns those letters by counting \section commands -- so the
    # roadmap is a claim about a file it does not live in. It shipped naming A through G of eight sections, while
    # the body sent the reader to Appendix H four times. Nothing caught it: the letters are correct individually,
    # the reference resolves because the body spells the letter out rather than using \ref, and a roadmap that
    # stops early reads exactly like a complete one.
    ap = f"{AN}/paper/appendix.tex"
    if os.path.exists(ap):
        aptex = open(ap, encoding="utf-8").read()
        have = {chr(ord("A") + i) for i in range(len(re.findall(r"^\\section\{", aptex, re.M)))}
        # The roadmap is read out of the appendix, where it is written, and not out of main.tex, where a second
        # copy of it used to be typed. The converter dropped the markdown's front matter as drafting scaffolding,
        # so the paragraph had to be hardcoded in the preamble file to reach the page at all -- and then a
        # language pass improved the markdown copy that nothing typeset, while the page kept the old wording for
        # weeks. Two copies of a paragraph is one copy and one thing that will go stale, so this reads the
        # region between the appendix's unnumbered heading and its first lettered section, and the next check
        # holds main.tex to carrying no prose of its own there.
        check(aptex.lstrip().startswith("\\section*{"), "the appendix opens with its own heading",
              aptex.lstrip()[:60])
        intro = aptex.split("\\section*{", 1)[-1].split("\\section{", 1)[0]
        stray = tex.split("\\appendix", 1)[-1].split("\\input{appendix}")[0]
        stray = "\n".join(ln for ln in stray.split("\n") if not ln.lstrip().startswith("%")).strip()
        check(not stray, "the appendix intro is written in one place", stray[:80])
        # A letter counts as named where the roadmap puts one: after "Appendix", or at a list position. Matching
        # any bare capital instead would count the article "A" as naming Appendix A.
        named = set(re.findall(r"(?:Appendices|Appendix|Section|,|\band)\s+([A-H])\b", re.sub(r"%.*", "", intro)))
        for a, b in re.findall(r"\b([A-Z])\s*-{2,}\s*([A-Z])\b", intro):     # "C--F" means C, D, E and F
            named |= {chr(c) for c in range(ord(a), ord(b) + 1)}
        cited = set(re.findall(r"Appendix ([A-Z])", open(f"{AN}/paper/body.tex", encoding="utf-8").read()))
        check(bool(have) and not have - named, "the appendix intro names every appendix section",
              f"{len(have)} sections, intro names {sorted(named)}, missing {sorted(have - named)}")
        check(not named - have, "the appendix intro names no section that does not exist",
              f"intro names {sorted(named - have)}, and the appendix has {sorted(have)}")
        check(not cited - have, "every appendix the body cites exists",
              f"the body cites {sorted(cited - have)}, and the appendix has {sorted(have)}")
        # Body section pointers are written as \S5 rather than \ref, for the same reason the appendix letters are
        # spelled out, and with the same consequence: deleting or reordering a section leaves every pointer past
        # it wrong and the compiler silent. Only the out-of-range case is decidable here; whether \S9 is the right
        # section for a given sentence is not, and is a reading job.
        body = open(f"{AN}/paper/body.tex", encoding="utf-8").read()
        n_sec = len(re.findall(r"^\\section\{", body, re.M))
        over = sorted({int(n) for n in re.findall(r"\\S(\d+)", body)} - set(range(1, n_sec + 1)))
        check(not over, "every section the body points at exists",
              f"the body points at {over}, and it has {n_sec} sections")

    # Appendix G states two counts of reproduce.py's own expectation table: how many of the paper's numbers the
    # script recomputes, and how many of those are bootstrap bounds it can only be asked to agree with loosely.
    # Both were typed once and then drifted a long way -- 194 against 465 rows, eight against 28 -- because a
    # count of a generated thing, written into prose, has nothing reading both sides of it. Every other number in
    # the manuscript is checked against the bundle by reproduce.py; these two are about reproduce.py, so they are
    # the two it structurally cannot check, which is why they went stale and nothing said so.
    apx = open(f"{AN}/APPENDIX.md", encoding="utf-8").read()
    rows = re.findall(r'^ +\("[^"]+", "[^"]+", [+-]?[\d.]+, ([\d.]+)\),',
                      open(f"{AN}/reproduce.py", encoding="utf-8").read(), re.M)
    if rows:
        # The regex above is a second implementation of "how long is that table", and a row it cannot match is a
        # row missing from both counts, which would then demand that the appendix print the short number. Import
        # the table and require the two to agree, so that the check below is about the appendix and not about
        # this pattern. main() is guarded in that script, so importing it runs only its definitions.
        spec = importlib.util.spec_from_file_location("_reproduce_for_audit", f"{AN}/reproduce.py")
        mod = importlib.util.module_from_spec(spec)
        try:
            spec.loader.exec_module(mod)
            check(len(rows) == len(mod.EXPECT), "the expectation table is counted the same two ways",
                  f"the row pattern finds {len(rows)} and reproduce.py's own table has {len(mod.EXPECT)}: "
                  f"a row the pattern cannot see is a row missing from appendix G's count")
        except Exception as exc:
            check(False, "reproduce.py's expectation table can be read",
                  f"importing it raised {type(exc).__name__}: {exc}")
        boot = sum(1 for tol in rows if float(tol) == BOOT_TOL)
        m = re.search(r"recomputes\s+\*\*([\d,]+)\*\* of this paper's numbers", apx)
        check(m is not None and int(m.group(1).replace(",", "")) == len(rows),
              "appendix G's count of the numbers reproduce.py checks",
              f"the appendix says {m.group(1) if m else 'nothing'}, the table has {len(rows)} rows")
        # Spelled out, because that is how the appendix writes a count that opens a sentence.
        said = re.search(r"(?m)^([A-Za-z-]+) of those numbers are bootstrap interval bounds", apx)
        check(said is not None and said.group(1).lower() == spell(boot),
              "appendix G's count of the bootstrap bounds",
              f"the appendix says {said.group(1) if said else 'nothing'}, "
              f"{boot} rows are checked to {BOOT_TOL} z")

    # The release list, against the release. Only the bullet block is read, so that section 10's sentence about
    # what is NOT redistributed is not mistaken for a promise to ship it.
    m = re.search(r"(?m)^The complete release contains the following[^\n]*\n\n((?:- .*\n)+)", apx)
    check(m is not None, "appendix G's release list is where the inventory check expects it",
          "no bullet block follows 'The complete release contains the following'")
    if m:
        bullets = [b[2:].strip() for b in m.group(1).strip().split("\n")]
        for phrase, pat in INVENTORY:
            here = [b for b in bullets if phrase in b]
            check(len(here) == 1, f"release list names {phrase!r} exactly once",
                  f"{len(here)} bullet(s) contain it")
            check(bool(glob.glob(f"{BUNDLE}/{pat}", recursive=True)),
                  f"the bundle has what {phrase!r} promises",
                  f"nothing matches {pat} under the bundle")
        loose = [b for b in bullets if not any(p in b for p, _ in INVENTORY)]
        check(not loose, "every bullet in the release list has an artifact behind it",
              f"{len(loose)} bullet(s) name nothing this check knows how to look for: {loose}")
        for bad in NO_SUCH_ARTIFACT:
            said_it = [b for b in bullets if bad in b]
            check(not said_it, f"the release list does not promise {bad!r}", f"{said_it}")

    print(f"\n{len(fails)} failing check(s), {len(warns)} warning(s)")
    for f in fails:
        print(f"  FAIL {f}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
